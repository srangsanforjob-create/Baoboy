const assert = require('assert');
const { resolveMonth } = require('./src/months');
const { parse } = require('./src/catalog');
const T = '2026-11', D = ['2026-11', '2026-12'];
const ok = (s, ym) => assert.deepStrictEqual(resolveMonth(s, T, D), { kind: 'ok', ym }, s);
ok('Nov', '2026-11'); ok('nov', '2026-11'); ok('พ.ย.', '2026-11'); ok('พย', '2026-11');
ok('พฤศจิกายน', '2026-11'); ok('เดือน พ.ย.', '2026-11'); ok('november', '2026-11'); ok('novembr', '2026-11');
ok('11', '2026-11'); ok('12', '2026-12'); ok('ธ.ค.', '2026-12'); ok('dec 2027', '2027-12');
ok('ม.ค.', '2027-01'); ok('ม.ค. 2569', '2026-01'); ok('2026-12', '2026-12'); ok('11/2026', '2026-11');
ok('Nov 26', '2026-11'); ok('nov 27', '2027-11'); ok('พ.ย. 26', '2026-11'); ok('พ.ย.27', '2027-11'); ok('พ.ย. 2569', '2026-11'); ok('พ.ย. 69', '2026-11'); ok('nov2027', '2027-11'); ok('11/26', '2026-11'); ok('11 27', '2027-11'); ok('ธ.ค. 2570', '2027-12');
ok('เดือนนี้', '2026-11'); ok('เดือนหน้า', '2026-12'); ok('เดือนที่แล้ว', '2026-10'); ok('next', '2026-12');
const a = resolveMonth('ma', T, D); assert.strictEqual(a.kind, 'ask'); assert.strictEqual(a.options.length, 2);
assert.strictEqual(resolveMonth('ju', T, D).kind, 'ask');
assert.strictEqual(resolveMonth('xyz', T, D).kind, 'none');
assert.strictEqual(resolveMonth('13', T, D).kind, 'none');
const p = parse('15 L2 R1 paid'); assert.strictEqual(p.day, 15); assert.strictEqual(p.status, 'paid');
assert.deepStrictEqual(p.items.map((i) => [i.pid, i.q]), [[0, 2], [1, 1]]);
assert.strictEqual(parse('สวัสดีครับ'), null); assert.strictEqual(parse('15'), null);
const q = parse('20 lagr 2 โรเซ 1 กระป๋อง 3'); assert.strictEqual(q.items[0].pid, null); assert.ok(q.items[0].c.length > 1);
assert.strictEqual(parse('5 pattaya 4').items[0].pid, 10);
console.log('all tests passed');
